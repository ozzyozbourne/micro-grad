#!/usr/bin/env python3
# Chapter 1 — a census of the tinygrad package: how many lines live where.
#
#   run:  python3 examples/01_repo_tour.py          (add --dump to write data/ch01_repo.json)
#
# Counts non-blank, non-comment lines of every .py file under the installed tinygrad package,
# grouped by directory. runtime/autogen/ (machine-generated ctypes bindings) is reported separately,
# because it is huge and nobody reads it by hand.
import pathlib, tinygrad

root = pathlib.Path(tinygrad.__file__).parent
def loc(p: pathlib.Path) -> int:
  return sum(1 for line in p.read_text(errors="ignore").splitlines() if line.strip() and not line.strip().startswith("#"))

per_dir: dict[str, int] = {}
files: list[tuple[int, str]] = []
autogen = 0
for f in sorted(root.rglob("*.py")):
  rel = f.relative_to(root.parent).as_posix()
  if "/runtime/autogen/" in rel:
    autogen += loc(f); continue
  n = loc(f)
  files.append((n, rel))
  d = str(pathlib.PurePosixPath(rel).parent)
  per_dir[d] = per_dir.get(d, 0) + n

total = sum(per_dir.values())
print(f"tinygrad package at {root}")
print(f"hand-written code: {total} lines in {len(files)} files  (+ {autogen} lines of autogenerated bindings in runtime/autogen)\n")
print(f"{'directory':34s} {'lines':>6s}")
for d, n in sorted(per_dir.items(), key=lambda kv: kv[0]):
  print(f"{d:34s} {n:6d}")

print("\nthe core compiler files (everything between Tensor and the generated code):")
core = ["tinygrad/tensor.py", "tinygrad/dtype.py", "tinygrad/helpers.py", "tinygrad/device.py", "tinygrad/uop/ops.py",
        "tinygrad/uop/__init__.py", "tinygrad/uop/symbolic.py", "tinygrad/uop/spec.py", "tinygrad/uop/weak.py",
        "tinygrad/schedule/__init__.py", "tinygrad/schedule/prepare.py", "tinygrad/schedule/indexing.py",
        "tinygrad/schedule/rangeify.py", "tinygrad/schedule/memory.py", "tinygrad/codegen/__init__.py",
        "tinygrad/codegen/opt/postrange.py", "tinygrad/codegen/opt/heuristic.py", "tinygrad/codegen/late/linearizer.py",
        "tinygrad/renderer/cstyle.py", "tinygrad/engine/realize.py", "tinygrad/runtime/ops_cpu.py"]
d = {rel: n for n, rel in files}
for rel in core: print(f"  {rel:40s} {d.get(rel, 0):5d}")
print(f"  {'(sum)':40s} {sum(d.get(r, 0) for r in core):5d}")

import sys, json
if "--dump" in sys.argv:   # writes data/ch01_repo.json for the repository explorer in chapter 1
  out = {"total": total, "autogen": autogen, "dirs": per_dir, "files": [{"path": rel, "lines": n} for n, rel in files]}
  p = pathlib.Path(__file__).resolve().parent.parent / "data" / "ch01_repo.json"
  p.write_text(json.dumps(out))
  print("wrote", p)
